void Bridge::setDriving(bool d)
{
    if (m_driving == d)
        return;
    m_driving = d;
    emit drivingChanged();
    // The distinct-cursor overlay only needs the agent-pointer feed while a
    // real-screen take-over is live; tail the fallback bus accordingly.
    if (d)
        startPointerTail();
    else
        stopPointerTail();
}

